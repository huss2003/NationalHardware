insert into suppliers(name)
select distinct supplier from stg s
where not exists(select 1 from suppliers x where x.name=s.supplier);

with norm as (
  select item_name, max(rate) rate,
     lower(trim(regexp_replace(item_name,'\s+',' ','g'))) nm
  from stg group by item_name
)
insert into products(name,prefix,category,gst_rate,unit,default_price,default_cost,active)
select distinct on (nm) item_name,'IMP','other',18,'pcs',rate,rate,true
from norm n
where not exists(
  select 1 from products p
  where lower(trim(regexp_replace(p.name,'\s+',' ','g')))=n.nm
)
order by nm, rate desc;

insert into purchases(supplier_id,bill_no,bill_date,subtotal,tax_total,grand_total,notes)
select sup.id, b.bill_no, b.bill_date, b.sub, b.tax, b.grand,
  'Purchase import 2026-06-11 (bill '||b.key||')'
from (select distinct key,bill_no,supplier,bill_date,sub,tax,grand from stg) b
join suppliers sup on sup.name=b.supplier
where not exists(
  select 1 from purchases p where p.notes='Purchase import 2026-06-11 (bill '||b.key||')'
);

insert into purchase_items(purchase_id,product_id,qty,rate,gst_rate,line_total)
select pu.id, prod.id, s.qty, s.rate, 18, s.line_total
from stg s
join purchases pu on pu.notes='Purchase import 2026-06-11 (bill '||s.key||')'
join lateral (
  select id from products p
  where lower(trim(regexp_replace(p.name,'\s+',' ','g')))
        = lower(trim(regexp_replace(s.item_name,'\s+',' ','g')))
  order by created_at desc limit 1
) prod on true
where not exists(
  select 1 from purchase_items pi where pi.purchase_id=pu.id
);